/**
 * Direction finding from non-isotropic (fixed UV) block textures.
 *
 * Convention: the top edge of the texture PNG is North when rotation is 0°.
 * Textures are loaded from the same assets published on mcasset.cloud
 * (misode/mcmeta 1.21.4-assets mirror on GitHub).
 */

export type DirectionTextureRotation = 0 | 90 | 180 | 270

export const DIRECTION_ROTATIONS: DirectionTextureRotation[] = [0, 90, 180, 270]

/** Minecraft version / asset tag used for remote textures and the local index. */
export const MC_ASSETS_VERSION = '1.21.4'

/**
 * Remote texture URL (mcasset.cloud-compatible assets via misode/mcmeta).
 * Example fileName: "crafting_table_top.png"
 */
export function remoteBlockTextureUrl(fileName: string): string {
  return `https://raw.githubusercontent.com/misode/mcmeta/${MC_ASSETS_VERSION}-assets/assets/minecraft/textures/block/${encodeURIComponent(fileName)}`
}

/** Bundled index of every block/*.png name (generated from mcmeta). */
/**
 * Textures that appear on the up / down face of a full cube model (generated by
 * scripts/generate-direction-textures.mjs). Single-texture blocks such as ores
 * are listed for both faces; plants, doors and partial blocks never are.
 */
export const FACE_TEXTURE_INDEX_URL = '/minecraft/textures/direction/block_face_textures.json'

export interface FaceTextureIndex {
  top: string[]
  bottom: string[]
}

/** Texture files offered for a face group; unknown groups offer top and bottom. */
export function texturesForFaceKind(
  index: FaceTextureIndex,
  kind: DirectionFaceKind | undefined,
): string[] {
  if (kind === 'top') return index.top
  if (kind === 'bottom') return index.bottom
  if (kind === 'side') return []
  return [...new Set([...index.top, ...index.bottom])]
}

export const BLOCK_TEXTURE_INDEX_URL = '/minecraft/textures/direction/block_textures.json'

export function textureDisplayName(fileName: string): string {
  return fileName
    .replace(/\.png$/i, '')
    .replace(/_/g, ' ')
}

export function searchDirectionLabel(degrees: DirectionTextureRotation): string {
  switch (degrees) {
    case 0:
      return 'North (0°)'
    case 90:
      return 'East (90°)'
    case 180:
      return 'South (180°)'
    case 270:
      return 'West (270°)'
  }
}

/** Prefer *_top and common station textures when ranking search results. */
export function textureSearchScore(fileName: string, query: string): number {
  const q = query.trim().toLowerCase()
  const name = fileName.toLowerCase()
  if (!q) {
    let score = 0
    if (name.includes('_top')) score += 50
    if (
      name.includes('crafting') ||
      name.includes('table') ||
      name.includes('furnace') ||
      name.includes('loom')
    ) {
      score += 20
    }
    if (name.includes('_ore') || name.includes('_block')) score += 5
    return score
  }
  const base = name.replace(/\.png$/, '')
  if (base === q || name === q) return 1000
  if (base.startsWith(q)) return 500
  const compact = q.replace(/\s+/g, '_')
  if (base.includes(compact)) return 300
  if (base.includes(q)) return 200
  const parts = q.split(/\s+/).filter(Boolean)
  if (parts.every((p) => base.includes(p))) return 150
  return -1
}

export function filterBlockTextures(all: string[], query: string, limit = 80): string[] {
  const scored = all
    .map((file) => ({ file, score: textureSearchScore(file, query) }))
    .filter((entry) => entry.score >= 0)
  scored.sort((a, b) => b.score - a.score || a.file.localeCompare(b.file))
  return scored.slice(0, limit).map((entry) => entry.file)
}

export type DirectionFaceKind = 'top' | 'bottom' | 'side'

/** Maps a world face direction to the texture group it can show. */
export function faceKindForDirection(face: string | undefined): DirectionFaceKind | undefined {
  if (face === 'up') return 'top'
  if (face === 'down') return 'bottom'
  if (face === 'north' || face === 'south' || face === 'east' || face === 'west') return 'side'
  return undefined
}
